/**
 * Compose the `apps/api/.env` and `apps/web/.env` bodies written by
 * `pnpm setup:env` (scripts/setup-local-env.mjs). Pure functions: no I/O.
 *
 * Inputs: the local Docker infrastructure settings (scripts/lib/dev-infra.mjs),
 * the previous env files (for re-run preservation) and generated secrets.
 *
 * Three kinds of keys:
 *
 *   1. Infrastructure (rewritten every run): DATABASE_URL, S3_*, SMTP_*,
 *      URLs and ports.
 *   2. Operator-controlled (preserved from the previous `apps/api/.env`):
 *      the AUTH_* feature flags and the OAuth client credentials. Flags default
 *      to `false`, credentials to empty (provider disabled).
 *   3. Secrets (generated once, then preserved): BETTER_AUTH_SECRET,
 *      MCP_KEY_PEPPER, AI_AGENT_ENCRYPTION_KEY.
 *
 * The web env mirrors the API flags (`NEXT_PUBLIC_AUTH_*`) instead of keeping
 * its own copy, so the SPA and the API can never disagree about which auth
 * flows exist.
 */

/** @typedef {Record<string, string | undefined>} EnvMap */
import { randomBytes } from 'node:crypto';

/** Boolean auth flags owned by the operator, all default `false`. */
export const AUTH_FLAG_KEYS = Object.freeze([
  'AUTH_FORGOT_PASSWORD_ENABLED',
  'AUTH_EMAIL_VERIFICATION_ENABLED',
  'AUTH_PASSWORDLESS_ENABLED',
]);

/** OAuth credentials owned by the operator; a provider is on when both are set. */
export const OAUTH_KEYS = Object.freeze({
  github: ['GITHUB_CLIENT_ID', 'GITHUB_CLIENT_SECRET'],
  google: ['GOOGLE_CLIENT_ID', 'GOOGLE_CLIENT_SECRET'],
  linkedin: ['LINKEDIN_CLIENT_ID', 'LINKEDIN_CLIENT_SECRET'],
});

/** Secrets generated on first run and preserved afterwards. */
export const SECRET_KEYS = Object.freeze([
  'BETTER_AUTH_SECRET',
  'MCP_KEY_PEPPER',
  'AI_AGENT_ENCRYPTION_KEY',
]);

const PLACEHOLDER_SECRETS = new Set(['', 'change-me-to-a-long-random-secret']);

/**
 * Parse a dotenv-style body. Comments and blank lines are ignored; values are
 * taken verbatim after the first `=` (quotes are not stripped).
 *
 * @param {string | null | undefined} contents
 * @returns {EnvMap}
 */
export function parseDotenv(contents) {
  /** @type {EnvMap} */
  const out = {};
  if (!contents) return out;
  for (const line of contents.split('\n')) {
    const trimmed = line.trim();
    if (trimmed === '' || trimmed.startsWith('#')) continue;
    const eq = trimmed.indexOf('=');
    if (eq === -1) continue;
    const key = trimmed.slice(0, eq).trim();
    const value = trimmed.slice(eq + 1).trim();
    if (key) out[key] = value;
  }
  return out;
}

/** @returns {string} 48 random bytes, base64url. */
export function generateSecret() {
  return randomBytes(48).toString('base64url');
}

/**
 * Operator-controlled values from the previous env files. Flags fall back to
 * the legacy `NEXT_PUBLIC_AUTH_*` web values, then `false`.
 *
 * @param {EnvMap} previousApiEnv
 * @param {EnvMap} [previousWebEnv]
 * @returns {EnvMap}
 */
export function readOperatorValues(previousApiEnv, previousWebEnv = {}) {
  /** @type {EnvMap} */
  const out = {};
  for (const key of AUTH_FLAG_KEYS) {
    const value = previousApiEnv[key] || previousWebEnv[`NEXT_PUBLIC_${key}`];
    out[key] = value === 'true' ? 'true' : 'false';
  }
  for (const keys of Object.values(OAUTH_KEYS)) {
    for (const key of keys) out[key] = previousApiEnv[key] ?? '';
  }
  return out;
}

/**
 * Keeps existing secrets; generates the missing or placeholder ones.
 *
 * @param {EnvMap} previousApiEnv
 * @param {() => string} [generate]
 * @returns {{ values: EnvMap; generated: string[] }}
 */
export function resolveSecrets(previousApiEnv, generate = generateSecret) {
  /** @type {EnvMap} */
  const values = {};
  const generated = [];
  for (const key of SECRET_KEYS) {
    const legacy =
      key === 'AI_AGENT_ENCRYPTION_KEY'
        ? previousApiEnv.IMPORT_LLM_CONFIG_ENCRYPTION_KEY
        : undefined;
    const existing = previousApiEnv[key] ?? legacy ?? '';
    if (PLACEHOLDER_SECRETS.has(existing)) {
      values[key] = generate();
      generated.push(key);
    } else {
      values[key] = existing;
    }
  }
  return { values, generated };
}

/**
 * @param {EnvMap} operator
 * @param {'github' | 'google' | 'linkedin'} provider
 */
function oauthEnabled(operator, provider) {
  return OAUTH_KEYS[provider].every((key) => Boolean(operator[key]));
}

/**
 * @param {{
 *   infra: ReturnType<typeof import('./dev-infra.mjs').devInfra>,
 *   port: string,
 *   webOrigin: string,
 *   publicApiUrl: string,
 *   pdfImportMaxBytes: string,
 *   pdfImportEnabled: string,
 *   operator: EnvMap,
 *   secrets: EnvMap,
 * }} input
 * @returns {string}
 */
export function composeApiEnv(input) {
  const { infra, operator, secrets } = input;
  return [
    '# Generated by `pnpm setup:env` — re-run after changing ports or infra.',
    '# Feature flags, OAuth credentials and secrets are preserved across runs.',
    '',
    '# Postgres (docker-compose.dev.yml)',
    `DATABASE_URL=${infra.databaseUrl}`,
    '',
    '# S3-compatible object storage (docker-compose.dev.yml)',
    `S3_ENDPOINT=${infra.s3.endpoint}`,
    `S3_PUBLIC_ENDPOINT=${infra.s3.endpoint}`,
    `S3_REGION=${infra.s3.region}`,
    `S3_ACCESS_KEY_ID=${infra.s3.accessKeyId}`,
    `S3_SECRET_ACCESS_KEY=${infra.s3.secretAccessKey}`,
    `S3_FORCE_PATH_STYLE=${infra.s3.forcePathStyle}`,
    `MEDIA_BUCKET=${infra.buckets.media}`,
    `MCP_EXPORT_BUCKET=${infra.buckets.mcpExports}`,
    '',
    `# SMTP — Mailpit catches every email (UI: ${infra.mailpitUrl})`,
    `SMTP_HOST=${infra.smtp.host}`,
    `SMTP_PORT=${infra.smtp.port}`,
    'SMTP_SECURE=false',
    'MAIL_FROM=Resubuild <no-reply@resubuild.local>',
    '',
    '# Server',
    `PORT=${input.port}`,
    `CORS_ORIGIN=${input.webOrigin}`,
    `APP_URL=${input.webOrigin}`,
    `WEB_URL=${input.webOrigin}`,
    `PUBLIC_API_URL=${input.publicApiUrl}`,
    '',
    '# Auth (Better Auth). Sessions are signed with BETTER_AUTH_SECRET.',
    `BETTER_AUTH_URL=${input.publicApiUrl}`,
    `BETTER_AUTH_SECRET=${secrets.BETTER_AUTH_SECRET}`,
    '',
    '# Auth feature flags (source of truth; apps/web/.env mirrors them)',
    ...AUTH_FLAG_KEYS.map((key) => `${key}=${operator[key]}`),
    '',
    '# OAuth providers — a provider is enabled when both values are set.',
    `# Callback URL to register: ${input.publicApiUrl}/api/auth/callback/<github|google|linkedin>`,
    ...Object.values(OAUTH_KEYS).flatMap((keys) => keys.map((key) => `${key}=${operator[key]}`)),
    '',
    '# MCP API keys (HMAC pepper)',
    `MCP_KEY_PEPPER=${secrets.MCP_KEY_PEPPER}`,
    '',
    '# PDF import + per-user AI agent / web scrape settings (keys configured in the app UI)',
    `AI_AGENT_ENCRYPTION_KEY=${secrets.AI_AGENT_ENCRYPTION_KEY}`,
    `PDF_IMPORT_MAX_BYTES=${input.pdfImportMaxBytes}`,
    `PDF_IMPORT_ENABLED=${input.pdfImportEnabled}`,
    '',
  ].join('\n');
}

/**
 * @param {{
 *   publicApiUrl: string,
 *   mailpitUrl: string,
 *   operator: EnvMap,
 * }} input
 * @returns {string}
 */
export function composeWebEnv(input) {
  const { operator } = input;
  return [
    '# Generated by `pnpm setup:env`.',
    '# Browser → Nest API over CORS (Bearer JSON).',
    `NEXT_PUBLIC_API_URL=${input.publicApiUrl}`,
    '',
    '# Auth feature flags — mirrored from apps/api/.env (edit them there and re-run',
    '# `pnpm setup:env`). Next.js inlines NEXT_PUBLIC_* at build time.',
    ...AUTH_FLAG_KEYS.map((key) => `NEXT_PUBLIC_${key}=${operator[key]}`),
    `NEXT_PUBLIC_AUTH_GITHUB_OAUTH_ENABLED=${oauthEnabled(operator, 'github')}`,
    `NEXT_PUBLIC_AUTH_GOOGLE_OAUTH_ENABLED=${oauthEnabled(operator, 'google')}`,
    `NEXT_PUBLIC_AUTH_LINKEDIN_OAUTH_ENABLED=${oauthEnabled(operator, 'linkedin')}`,
    '',
    '# Dev-only hint linking auth screens to the local mail catcher',
    `NEXT_PUBLIC_DEV_MAILPIT_URL=${input.mailpitUrl}`,
    '',
  ].join('\n');
}
